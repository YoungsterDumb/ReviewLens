export const dictionaries = { vi, en } as const
export type UiLang = keyof typeof dictionaries
export type TKey = Key
export type TFn = (key: TKey, vars?: Record<string, string | number>) => string

export function translate(lang: UiLang, key: TKey, vars?: Record<string, string | number>): string {
  const template = dictionaries[lang][key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m))
}

interface I18nValue {
  lang: UiLang
  setLang: (l: UiLang) => void
  t: TFn
}

const I18nContext = createContext<I18nValue | null>(null)

function initialLang(): UiLang {
  try {
    const saved = localStorage.getItem('rl-lang')
    if (saved === 'vi' || saved === 'en') return saved
  } catch {
    /* storage unavailable */
  }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('en') ? 'en' : 'vi'
}

export function I18nProvider({ children, lang: forced }: { children: ReactNode; lang?: UiLang }) {
  const [lang, setLangState] = useState<UiLang>(forced ?? initialLang)
  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])
  const setLang = useCallback((l: UiLang) => {
    setLangState(l)
    try {
      localStorage.setItem('rl-lang', l)
    } catch {
      /* storage unavailable */
    }
  }, [])
  const value = useMemo<I18nValue>(() => ({ lang, setLang, t: (k, v) => translate(lang, k, v) }), [lang, setLang])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used inside <I18nProvider>')
  return ctx
}
